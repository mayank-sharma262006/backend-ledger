//this file contains the controller functions
//  for user authentication
//what it doues is that it handles the logic for
//  user registration, login, and other 
// authentication-related operations. 
// It interacts with the user model to perform
//  database operations and returns appropriate
//  responses to the client.
const jwt = require("jsonwebtoken");
//usermodel required to interact with the user collection in the database
//usermodel is a Mongoose model that represents the "User" 
// collection in the MongoDB database. It provides methods to
//  create, read, update, and delete user documents in the collection.
//  The controller functions use this model to perform database
//  operations related to user authentication.
const userModel = require("../models/user.models");
//user register controller 
const { sendRegistrationEmail } = require("../services/email.service");
//post /api/auth/register
//this function handles the user registration process
async function userRegisterConstroller(req, res) {
    const { name, email, password } = req.body;
    //check if user already exists
    const existingUser = await userModel.findOne({ email });
    if(existingUser) {
        return res.status(400).json({ message: "User already exists",
             status: "failed" });
    }
    //create the new user in the database
    const user = await userModel.create({ name, email, password });
    //user id is generated by the database when a new user document is created.
    //userid is a built in feature of mongodb and mongoose,
    //  which automatically generates a unique identifier for
    //  each document in the collection.
    // what does this token do? The token is a JSON Web Token
    //  (JWT) that is generated after a successful user registration.
    //  It contains encoded information about the user, such
    //  as their unique identifier (user_Id). The token is
    //  signed using a secret key (process.env.JWT_SECRET) to
    //  ensure its integrity and authenticity. The token is
    //  set to expire in 3 days, meaning the user will need 
    // to re-authenticate after that period. The token is then
    //  sent back to the client as an HTTP-only cookie, which helps
    //  in maintaining user sessions and authentication for subsequent
    //  requests.
    //the cookie is stored in the user's browser and is sent with each subsequent
    //  request to the server, allowing the server to identify and authenticate
    //  the user.
    const token = jwt.sign({user_Id : user._id}, process.env.JWT_SECRET, { expiresIn: "3d" });
    //this line sets the token as an HTTP-only cookie in the response.

    res.cookie("token", token, {
        httpOnly: true,
        expires: new Date(Date.now() + 3 * 24 * 60 * 60 * 1000), // 3 days
    });
    res.status(201).json({user : {
        user_id : user._id, 
        username : user.name,
        email : user.email,
    },token: token, message: "User registered successfully", status: "success" });
    await sendRegistrationEmail(user.email, user.name);
}
//user login controller
//post /api/auth/login
async function userLoginController(req, res) {
    const { email, password } = req.body;
    const existingUser = await userModel.findOne({ email}).select("+password");
    if(!existingUser) { 
        return res.status(401).json({ message: "User does not exist", status: "failed" });
    }
    const comparePassword = await existingUser.comparePassword(password);
    if(!comparePassword) {
        // return res.status(401).json({ message: "Invalid credentials", status: "failed" });
        return res.status(401).json({ message: "User does not exist", status: "failed" });
    }
    const token = jwt.sign({user_Id : existingUser._id}, process.env.JWT_SECRET, { expiresIn: "3d" });
    //this line sets the token as an HTTP-only cookie in the response.
    //the res is stored in cookie because it is a secure
    //  way to store the token on the client side.
    //when a request is made to the server, the cookie
    //  is automatically sent along with the request headers,
    //  allowing the server to verify the user's authentication status.
    //which is done by checking the token in the cookie against the 
    // secret key used to sign it.
    res.cookie("token", token, {
        httpOnly: true,
        expires: new Date(Date.now() + 3 * 24 * 60 * 60 * 1000), // 3 days
    });

    res.status(201).json({user : {
        user_id : existingUser._id, 
        username : existingUser.name,
        email : existingUser.email,
    },token: token, message: "User logged in successfully", status: "success" });

}
module.exports = { userRegisterConstroller, userLoginController }